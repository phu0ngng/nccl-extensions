#!/usr/bin/env bash
# Build the review evidence pack for a change: see tools/README.md.
#
# Usage: review_prep.sh <base-rev> <head-rev> [out-dir]
#
# Steps (each writes its artifact or a "skipped: <reason>" line in INDEX.md):
#   1. diff.patch, hunks.md
#   2. build base and head (lib + tests), DEBUG=0 and DEBUG=1 for the lib; warnings diff
#   3. res_usage_diff.md from both libnccl_ep.so
#   4. run the touched tests on each side with a fresh JIT cache; tests_<side>.log
#   5. compile every cached JIT variant offline with -Xptxas -v; jit_diff.md
#   6. compute-sanitizer on the head tests
# Mutation runs are separate: tools/mutate_and_run.sh.
set -euo pipefail

BASE="${1:?base rev}"
HEAD_REV="${2:?head rev}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(git -C "${HERE}" rev-parse --show-toplevel)"
OUT="${3:-${REPO}/../review-evidence}"
mkdir -p "${OUT}"
OUT="$(cd "${OUT}" && pwd)"
INDEX="${OUT}/INDEX.md"
JOBS="${REVIEW_JOBS:-$(nproc)}"
export CUDA_HOME="${CUDA_HOME:-/usr/local/cuda}"
export NCCL_HOME="${NCCL_HOME:-${REPO}/third_party/nccl/build}"
GPUS="${REVIEW_GPUS:-$(nvidia-smi -L 2>/dev/null | wc -l || echo 0)}"
SANITIZERS="${REVIEW_SANITIZERS-initcheck memcheck}"

note() { echo "- $*" >> "${INDEX}"; echo "[review_prep] $*"; }
skipped() { note "**skipped** $1: $2"; }

BASE_SHA="$(git -C "${REPO}" rev-parse --verify "${BASE}^{commit}")"
HEAD_SHA="$(git -C "${REPO}" rev-parse --verify "${HEAD_REV}^{commit}")"
cat > "${INDEX}" <<EOF
# Review evidence pack

- base: \`${BASE_SHA}\` (${BASE})
- head: \`${HEAD_SHA}\` (${HEAD_REV})
- host: $(hostname), nvcc: $("${CUDA_HOME}/bin/nvcc" --version 2>/dev/null | grep -o 'release [0-9.]*' || echo unavailable), GPUs: ${GPUS}
- generated by tools/review_prep.sh; every artifact path below is relative to this directory

## Artifacts
EOF

# 1. Diff and hunk summary
git -C "${REPO}" diff "${BASE_SHA}" "${HEAD_SHA}" > "${OUT}/diff.patch"
python3 -I "${HERE}/hunks.py" "${OUT}/diff.patch" > "${OUT}/hunks.md"
note "\`diff.patch\`, \`hunks.md\`: $(git -C "${REPO}" diff --shortstat "${BASE_SHA}" "${HEAD_SHA}")"
TOUCHED_TESTS="${REVIEW_TESTS:-$(git -C "${REPO}" diff --name-only "${BASE_SHA}" "${HEAD_SHA}" -- 'nccl_ep/tests/test_*.cu' | xargs -rn1 basename | sed 's/\.cu$//' | tr '\n' ' ')}"
TOUCHES_LIB="$(git -C "${REPO}" diff --name-only "${BASE_SHA}" "${HEAD_SHA}" -- 'nccl_ep/*.cc' 'nccl_ep/*.h' 'nccl_ep/*.hpp' 'nccl_ep/device/' 'nccl_ep/include/' | head -1)"

# 2. Worktrees and builds
worktree() {
    local side="$1" sha="$2" dir="${OUT}/src_${side}"
    if [[ ! -d "${dir}" ]]; then
        git -C "${REPO}" worktree add --detach "${dir}" "${sha}" > /dev/null 2>&1
    fi
    echo "${dir}"
}
build_side() {
    local side="$1" sha="$2"
    local tree build log
    tree="$(worktree "${side}" "${sha}")"
    build="${OUT}/build_${side}"
    log="${OUT}/build_${side}.log"
    if [[ -n "${REVIEW_SKIP_BUILD:-}" && -f "${build}/lib/libnccl_ep.so" ]]; then
        note "build_${side}: reused (REVIEW_SKIP_BUILD)"
        return 0
    fi
    : > "${log}"
    if make -C "${tree}/nccl_ep" -j"${JOBS}" lib BUILDDIR="${build}" DEBUG=0 >> "${log}" 2>&1 \
       && make -C "${tree}/nccl_ep" -j"${JOBS}" lib BUILDDIR="${build}_debug" DEBUG=1 >> "${log}" 2>&1 \
       && make -C "${tree}/nccl_ep/tests" -j"${JOBS}" BUILDDIR="${build}" >> "${log}" 2>&1; then
        note "build_${side}: ok (lib DEBUG=0 and DEBUG=1, tests); log \`build_${side}.log\`"
    else
        note "**build_${side}: FAILED**; see \`build_${side}.log\` (last lines below)"
        tail -n 30 "${log}" | sed 's/^/      /' >> "${INDEX}"
        return 1
    fi
}
BUILD_OK=1
if ! command -v "${CUDA_HOME}/bin/nvcc" > /dev/null 2>&1; then
    skipped "builds" "no nvcc at ${CUDA_HOME}/bin/nvcc"
    BUILD_OK=0
elif [[ ! -d "${NCCL_HOME}/include" ]]; then
    skipped "builds" "no NCCL build at NCCL_HOME=${NCCL_HOME}"
    BUILD_OK=0
else
    build_side base "${BASE_SHA}" || BUILD_OK=0
    build_side head "${HEAD_SHA}" || BUILD_OK=0
fi

if (( BUILD_OK )); then
    python3 -I "${HERE}/warnings_diff.py" "${OUT}/build_base.log" "${OUT}/build_head.log" > "${OUT}/warnings_new.md"
    note "\`warnings_new.md\`: $(grep -m1 '^## New' "${OUT}/warnings_new.md")"
    # 3. Static kernel resource usage
    if command -v "${CUDA_HOME}/bin/cuobjdump" > /dev/null 2>&1 || command -v cuobjdump > /dev/null 2>&1; then
        PATH="${CUDA_HOME}/bin:${PATH}" python3 -I "${HERE}/res_usage_diff.py" \
            "${OUT}/build_base/lib/libnccl_ep.so" "${OUT}/build_head/lib/libnccl_ep.so" > "${OUT}/res_usage_diff.md"
        note "\`res_usage_diff.md\`: $(grep -m1 '^## Changed' "${OUT}/res_usage_diff.md"), $(grep -m1 '^## Only in head' "${OUT}/res_usage_diff.md")"
    else
        skipped "res_usage_diff.md" "no cuobjdump"
    fi
else
    skipped "warnings_new.md, res_usage_diff.md, test runs, JIT variants, sanitizer" "build unavailable"
fi

# 4a. Host-only touched tests (no test_common.h, so no communicator and no GPU) run on any node.
host_only_tests() {
    local tree="$1" t
    for t in ${TOUCHED_TESTS}; do
        if [[ -f "${tree}/nccl_ep/tests/${t}.cu" ]] && ! grep -q 'test_common.h' "${tree}/nccl_ep/tests/${t}.cu"; then
            echo "${t}"
        fi
    done
}
run_host_tests_side() {
    local side="$1"
    local build="${OUT}/build_${side}" log="${OUT}/tests_host_${side}.log" fail=0 ran=""
    export LD_LIBRARY_PATH="${build}/lib:${NCCL_HOME}/lib:${LD_LIBRARY_PATH:-}"
    : > "${log}"
    for t in $(host_only_tests "${OUT}/src_${side}"); do
        ran+="${t} "
        if [[ -x "${build}/test/nccl_ep/${t}" ]]; then
            echo "=== ${t} ===" >> "${log}"
            "${build}/test/nccl_ep/${t}" >> "${log}" 2>&1 || fail=1
        else
            echo "missing binary ${t}" >> "${log}"; fail=1
        fi
    done
    if [[ -z "${ran}" ]]; then
        return 0
    fi
    if (( fail )); then
        note "**tests_host_${side}: FAILED**; see \`tests_host_${side}.log\` (host-only tests: ${ran})"
    else
        note "tests_host_${side}: passed (host-only, no GPU: ${ran}); log \`tests_host_${side}.log\`"
    fi
}
if (( BUILD_OK )) && [[ -n "${TOUCHED_TESTS}" ]]; then
    run_host_tests_side base
    run_host_tests_side head
fi

# 4b. Run touched tests with a fresh JIT cache on each side
run_tests_side() {
    local side="$1"
    local build="${OUT}/build_${side}" log="${OUT}/tests_${side}.log" fail=0
    export LD_LIBRARY_PATH="${build}/lib:${NCCL_HOME}/lib:${LD_LIBRARY_PATH:-}"
    export NCCL_EP_JIT_CACHE_DIR="${OUT}/jit_${side}/cache"
    export NCCL_EP_JIT_SOURCE_DIR="${build}/include/nccl_ep"
    # NCCL's own headers (nccl.h, nccl_device/); in CI the two trees share one prefix.
    export NCCL_EP_JIT_BUILD_INCLUDE_DIR="${NCCL_HOME}/include"
    export NCCL_EP_JIT_CUDA_INCLUDE_DIR="${CUDA_HOME}/include"
    export NCCL_EP_JIT_LOG=1
    rm -rf "${NCCL_EP_JIT_CACHE_DIR}"; mkdir -p "${NCCL_EP_JIT_CACHE_DIR}"
    : > "${log}"
    for t in ${TOUCHED_TESTS}; do
        if [[ ! -x "${build}/test/nccl_ep/${t}" ]]; then
            echo "missing binary ${t}" >> "${log}"; fail=1; continue
        fi
        REVIEW_LOG_DIR="${OUT}/tests_${side}_${t}_logs" \
        "${HERE}/run_tests_sanitized.sh" "${build}/test/nccl_ep/${t}" "${GPUS}" none >> "${log}" 2>&1 || fail=1
    done
    if (( fail )); then
        note "**tests_${side}: FAILED or missing**; see \`tests_${side}.log\`"
    else
        note "tests_${side}: passed (${TOUCHED_TESTS:-none}); JIT variants compiled: $(find "${NCCL_EP_JIT_CACHE_DIR}" -name kernel.cu | wc -l)"
    fi
}
if (( BUILD_OK )) && [[ -n "${TOUCHED_TESTS}" ]] && (( GPUS >= 4 )); then
    run_tests_side base
    run_tests_side head
elif (( BUILD_OK )); then
    skipped "test runs" "touched tests: '${TOUCHED_TESTS:-none}', GPUs: ${GPUS} (need 4)"
fi

# 5a. No test run filled a JIT cache: generate the sources for a fixed configuration matrix
#     instead (tools/jit_enumerate.sh). Static compile only; it shows which variants build and
#     their ptxas numbers, not which ones the tests reach.
JIT_SOURCE_NOTE="the variants in \`jit_head/variants.tsv\` are exactly those the touched tests reach; a variant the change adds that is absent there was not executed by any test"
if (( BUILD_OK )) && [[ ! -d "${OUT}/jit_head/cache" ]]; then
    enum_ok=1
    for side in base head; do
        if ! "${HERE}/jit_enumerate.sh" "${OUT}/src_${side}" "${OUT}/build_${side}" "${OUT}/jit_${side}/cache" \
                > "${OUT}/jit_${side}_enumerate.log" 2>&1; then
            enum_ok=0
            skipped "jit_${side} enumeration" "$(tail -n 1 "${OUT}/jit_${side}_enumerate.log")"
        fi
    done
    if (( enum_ok )); then
        JIT_SOURCE_NOTE="JIT sources were generated by \`tools/jit_enumerate.cu\` for a fixed configuration matrix (bf16 tokens, hidden 7168 and 256, top-k 8, both layouts, every LSA mode and CFT sender mode); this shows which variants compile and their static numbers, not which ones any test reaches"
    else
        rm -rf "${OUT}/jit_base/cache" "${OUT}/jit_head/cache"
    fi
fi

# 5b. Offline compile of every JIT variant with ptxas -v, both sides
if (( BUILD_OK )) && [[ -d "${OUT}/jit_head/cache" ]]; then
    # compute_cap prints "8.9"; the JIT targets sm_<major><minor> of the device it runs on.
    CC="$(nvidia-smi --query-gpu=compute_cap --format=csv,noheader 2>/dev/null | head -1 | tr -d '. ' || true)"
    ARCH="${REVIEW_ARCH:-${CC:+sm_${CC}}}"
    ARCH="${ARCH:-sm_90}"
    for side in base head; do
        build="${OUT}/build_${side}"
        PATH="${CUDA_HOME}/bin:${PATH}" python3 -I "${HERE}/jit_variants.py" compile "${OUT}/jit_${side}/cache" "${OUT}/jit_${side}/variants.tsv" \
            --arch "${ARCH}" --source-dir "${build}/include/nccl_ep" --build-include-dir "${NCCL_HOME}/include" \
            --cuda-include-dir "${CUDA_HOME}/include" --jobs "${JOBS}" > "${OUT}/jit_${side}/compile.log" 2>&1 || true
    done
    python3 -I "${HERE}/jit_variants.py" diff "${OUT}/jit_base/variants.tsv" "${OUT}/jit_head/variants.tsv" > "${OUT}/jit_diff.md"
    note "\`jit_diff.md\` (arch ${ARCH}): $(grep -m1 '^## Compile failures' "${OUT}/jit_diff.md"); per-variant tables in \`jit_<side>/variants.tsv\`"
    note "JIT coverage: ${JIT_SOURCE_NOTE}"
elif (( BUILD_OK )); then
    skipped "jit_diff.md" "no JIT cache (tests did not run) and no generated sources"
fi

# 6. Sanitizers on head
if (( BUILD_OK )) && [[ -n "${TOUCHED_TESTS}" && -n "${SANITIZERS}" ]] && (( GPUS >= 4 )) && command -v compute-sanitizer > /dev/null 2>&1; then
    export LD_LIBRARY_PATH="${OUT}/build_head/lib:${NCCL_HOME}/lib:${LD_LIBRARY_PATH:-}"
    export NCCL_EP_JIT_CACHE_DIR="${OUT}/jit_head/cache"
    for tool in ${SANITIZERS}; do
        : > "${OUT}/sanitizer_${tool}.log"; fail=0
        for t in ${TOUCHED_TESTS}; do
            REVIEW_LOG_DIR="${OUT}/sanitizer_${tool}_${t}_logs" \
            "${HERE}/run_tests_sanitized.sh" "${OUT}/build_head/test/nccl_ep/${t}" "${GPUS}" "${tool}" >> "${OUT}/sanitizer_${tool}.log" 2>&1 || fail=1
        done
        if (( fail )); then note "**sanitizer_${tool}: errors**; see \`sanitizer_${tool}.log\`"; else note "sanitizer_${tool}: clean"; fi
    done
elif (( BUILD_OK )); then
    skipped "sanitizers" "needs compute-sanitizer, 4 GPUs and touched tests (have: $(command -v compute-sanitizer > /dev/null && echo sanitizer || echo no-sanitizer), ${GPUS} GPUs, '${TOUCHED_TESTS:-none}')"
fi

cat >> "${INDEX}" <<EOF

## Notes for critics
- Formatting is not checked here: \`.clang-format-ignore\` excludes \`nccl_ep/\`.
- Static numbers (\`res_usage_diff.md\`, \`jit_diff.md\`) are registers, spills, shared, stack and SASS instruction counts, not latency. A speedup claim still needs a measurement.
- Library code touched: $(if [[ -n "${TOUCHES_LIB}" ]]; then echo yes; else echo no; fi). Touched tests: ${TOUCHED_TESTS:-none}.
- Mutation experiments need the head worktree and build (\`src_head/\`, \`build_head/\` under the pack's
  output directory while it exists): \`tools/mutate_and_run.sh <src_head> <build_head> <patch> <test> <gpus>\`.
- Architecture built: \`${NVCC_GENCODE:-the project default}\`.
EOF
echo "[review_prep] done: ${INDEX}"
